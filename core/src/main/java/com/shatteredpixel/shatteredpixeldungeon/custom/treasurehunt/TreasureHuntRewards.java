public final class TreasureHuntRewards {

	private static final int ORDINARY_REWARD_SCORE = 500;

	private static final List<Class<? extends Item>> ORDINARY_POTIONS =
			Arrays.<Class<? extends Item>>asList(
					PotionOfHealing.class,
					PotionOfMindVision.class,
					PotionOfFrost.class,
					PotionOfLiquidFlame.class,
					PotionOfToxicGas.class,
					PotionOfHaste.class,
					PotionOfInvisibility.class,
					PotionOfLevitation.class,
					PotionOfParalyticGas.class,
					PotionOfPurity.class);

	private static final List<Class<? extends Item>> ORDINARY_SCROLLS =
			Arrays.<Class<? extends Item>>asList(
					ScrollOfIdentify.class,
					ScrollOfRemoveCurse.class,
					ScrollOfMirrorImage.class,
					ScrollOfRecharging.class,
					ScrollOfTeleportation.class,
					ScrollOfLullaby.class,
					ScrollOfMagicMapping.class,
					ScrollOfRage.class,
					ScrollOfRetribution.class,
					ScrollOfTerror.class);

	private static final List<Class<? extends Item>> ORDINARY_STONES =
			Arrays.<Class<? extends Item>>asList(
					StoneOfIntuition.class,
					StoneOfDetectMagic.class,
					StoneOfFlock.class,
					StoneOfShock.class,
					StoneOfBlink.class,
					StoneOfDeepSleep.class,
					StoneOfClairvoyance.class,
					StoneOfAggression.class,
					StoneOfBlast.class,
					StoneOfFear.class);

	private static final List<Class<? extends Item>> ORDINARY_SEEDS =
			Arrays.<Class<? extends Item>>asList(
					Sungrass.Seed.class,
					Fadeleaf.Seed.class,
					Icecap.Seed.class,
					Firebloom.Seed.class,
					Sorrowmoss.Seed.class,
					Swiftthistle.Seed.class,
					Blindweed.Seed.class,
					Stormvine.Seed.class,
					Earthroot.Seed.class,
					Mageroyal.Seed.class);

	private TreasureHuntRewards() {
	}

	public static Class<? extends Item> tenStepRewardClass(
			int score, boolean completedTenSteps, Random random) {
		if (random == null) {
			throw new IllegalArgumentException("random must not be null");
		}

		if (completedTenSteps) {
			return random.nextBoolean()
					? PotionOfExperience.class
					: ScrollOfTransmutation.class;
		}

		List<Class<? extends Item>> pool;
		if (score > ORDINARY_REWARD_SCORE) {
			pool = random.nextBoolean() ? ORDINARY_POTIONS : ORDINARY_SCROLLS;
		} else {
			pool = random.nextBoolean() ? ORDINARY_STONES : ORDINARY_SEEDS;
		}
		return pool.get(random.nextInt(pool.size()));
	}

	public static Item createTenStepReward(
			int score, boolean completedTenSteps, Random random) {
		return Reflection.newInstance(
				tenStepRewardClass(score, completedTenSteps, random));
	}

	public static Item grantTenStepReward(
			Hero hero, int score, boolean completedTenSteps) {
		Item reward = createTenStepReward(
				score, completedTenSteps, new Random(System.nanoTime()));
		if (hero != null && hero.belongings != null
				&& reward.collect(hero.belongings.backpack)) {
			return reward;
		}

		if (hero != null && Dungeon.level != null) {
			Heap heap = Dungeon.level.drop(reward, hero.pos);
			if (heap != null && heap.sprite != null) {
				heap.sprite.drop();
			}
		}
		return reward;
	}
}
